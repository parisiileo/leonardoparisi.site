/** The visible project list, mirrored so the work section is machine-readable. */
function workSchema(locale: string) {
  return {
    "@type": "ItemList",
    "@id": `${localeUrl(locale)}#work`,
    name: "Selected work",
    numberOfItems: data.work.length,
    itemListElement: data.work.map((project, index) => ({
      "@type": "ListItem",
      position: index + 1,
      item: {
        "@type": "CreativeWork",
        name: project.company,
        url: project.url,
        author: { "@id": ID.person },
        keywords: project.stack.join(", "),
      },
    })),
  };
}

/**
 * One `@graph` per page instead of a handful of loose blocks: the nodes
 * reference each other by `@id`, which is what lets a crawler resolve the
 * person, the business and the page into a single entity.
 */
export function generateGraph({
  locale,
  title,
  description,
  jobTitle,
  businessName,
}: {
  locale: string;
  title: string;
  description: string;
  jobTitle: string;
  businessName: string;
}) {
  const url = localeUrl(locale);

  return {
    "@context": "https://schema.org",
    "@graph": [
      websiteSchema(locale, title, description),
      {
        "@type": "ProfilePage",
        "@id": `${url}#page`,
        url,
        name: title,
        description,
        inLanguage: locale,
        isPartOf: { "@id": ID.website },
        about: { "@id": ID.person },
        mainEntity: { "@id": ID.person },
        primaryImageOfPage: ogImage,
      },
      personSchema(locale, jobTitle, description),
      businessSchema(businessName, description),
      workSchema(locale),
    ],
  };
}

/** Legal pages: a plain WebPage plus the breadcrumb back to the portfolio. */
export function generateLegalGraph({
  locale,
  slug,
  title,
  description,
  homeLabel,
}: {
  locale: string;
  slug: string;
  title: string;
  description: string;
  homeLabel: string;
}) {
  const url = `${localeUrl(locale)}/${slug}`;

  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "WebPage",
        "@id": `${url}#page`,
        url,
        name: title,
        description,
        inLanguage: locale,
        isPartOf: { "@id": ID.website },
        publisher: { "@id": ID.person },
      },
      {
        "@type": "BreadcrumbList",
        "@id": `${url}#breadcrumb`,
        itemListElement: [
          {
            "@type": "ListItem",
            position: 1,
            name: homeLabel,
            item: localeUrl(locale),
          },
          { "@type": "ListItem", position: 2, name: title, item: url },
        ],
      },
    ],
  };
}
