const domain = process.env.NEXT_PUBLIC_DOMAIN || "imleo.it";

/** English lives at the root; every other locale gets a path prefix. */
export function localeUrl(locale: string) {
  const base = `https://${domain}`;
  return locale === "en" ? base : `${base}/${locale}`;
}

/**
 * Google wants a language-region pair whenever the audience is regional. This
 * site is aimed at Alto Adige / Südtirol first, so `it` and `de` both carry
 * regional twins and the bare code stays as the catch-all.
 */
export const HREFLANG: Record<string, string[]> = {
  en: ["en", "en-GB", "en-US"],
  it: ["it", "it-IT"],
  de: ["de", "de-DE", "de-AT", "de-CH"],
  es: ["es", "es-ES"],
};

/** Builds the `alternates.languages` map for any path under a locale root. */
export function languageAlternates(suffix = "") {
  const languages: Record<string, string> = {};
  for (const locale of routing.locales) {
    for (const tag of HREFLANG[locale] ?? [locale]) {
      languages[tag] = `${localeUrl(locale)}${suffix}`;
    }
  }
  languages["x-default"] = `${localeUrl(routing.defaultLocale)}${suffix}`;
  return languages;
}

